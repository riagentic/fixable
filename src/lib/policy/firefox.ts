// Firefox preferences. The browser is the largest privacy and security surface
// on a workstation, and almost all of it is one boolean away from being better.
//
// What is deliberately NOT here: `privacy.resistFingerprinting`, `webgl.disabled`
// and `media.peerconnection.enabled`. Each is a real hardening win and each
// visibly breaks ordinary browsing — video calls, maps, timezone-correct pages.
// A fix that makes the machine worse to use is not a fix.
import type { MozPolicy } from "../../type/policy.ts";

/** [id, pref, fallback, bad, safe, weight, title, detail, because] */
