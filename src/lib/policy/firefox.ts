const ROWS: Row[] = [...TELEMETRY, ...CONTENT, ...NETWORK, ...SECURITY];

const category = (id: string): MozPolicy["category"] =>
  SECURITY.some((r) => r[0] === id)
    ? "security"
    : NETWORK.some((r) => r[0] === id)
    ? "privacy"
    : "privacy";

export const FIREFOX_POLICIES: MozPolicy[] = ROWS.map(
  ([id, pref, fallback, bad, safe, weight, title, detail, because]) => ({
    id: `ff-${id}`,
    title,
    category: category(id),
    severity: weight >= 75 ? "major" as const : "minor" as const,
    weight,
    product: "firefox" as const,
    pref,
    fallback,
    bad,
    safe,
    detail,
    because,
  }),
);
